"""给 VLM 的中文提示词。

回答纪律：只描述画面里明确看得见的内容；看不清就说看不清；价格/日期等数字
一律交给 OCR 原文与确定性解析，VLM 不负责报数字。
"""

from __future__ import annotations

#: 所有场景提示词共用的纪律段落
GROUNDING_RULE = (
    "只根据画面里明确看得见的内容回答，看不清就说“看不清”，不要猜测，不要编造。"
    "不要报价格、金额或日期数字，这类信息由文字识别负责。"
)


def describe_prompt(question: str) -> str:
    """描述/问答类：用一两句口语中文回答。"""
    return (
        "你是一台帮助视障用户看东西的助手。"
        f"用户问：{question.strip()}\n"
        "请用一两句简单、口语化的中文回答，先说最要紧的结论，可以说颜色、数量、"
        "物体和大致位置。"
        f"{GROUNDING_RULE}"
        "不要使用 Markdown，不要分点，不超过 60 个字。"
    )


def find_object_prompt(target: str, *, max_candidates: int = 2) -> str:
    """找物：只返回 JSON 数组，便于确定性解析。"""
    return (
        "你是一台帮助视障用户找东西的助手。"
        f"请在画面里找“{target}”。最多给出 {max_candidates} 个可分辨的候选，"
        "按把握从大到小排列。"
        "只输出一个 JSON 数组，不要任何解释或代码块标记。数组元素格式："
        '{"label":"物品名称","position":"画面中的位置，如左上方/正中间/右侧",'
        '"box":[x1,y1,x2,y2],"feature":"可分辨特征，如颜色/形状",'
        '"confidence":0到1的小数}。'
        "box 用 0 到 1000 的归一化坐标，左上角为原点；box 要框住整个物品。"
        "画面里没有这个物品时输出空数组 []。"
        f"{GROUNDING_RULE}"
    )


def read_text_prompt(question: str) -> str:
    """读字兜底：OCR 一行都没读到但用户要求读字时，让 VLM 描述可见文字。"""
    return (
        "你是一台帮助视障用户读字的助手。"
        f"用户要求：{question.strip()}\n"
        "请把画面里清楚可见的文字按从上到下、从左到右念出来，保留原文，不要翻译、"
        "不要补全、不要改数字。一个字都看不清就只回答“看不清”。"
        "不要使用 Markdown，不超过 80 个字。"
    )


def compare_prompt(question: str) -> str:
    """两图比较兜底：结构化字段没读全时，只描述两边可见的差异。

    VLM 不负责价格/日期数字；命中不了 OCR 口径时，用它补上“各是什么、
    最明显的区别”，避免只回一句“都没读全”。
    """
    return (
        "你是一台帮助视障用户比较两件东西的助手。左边是A，右边是B，中间有白色分隔线。"
        f"用户要求：{question.strip()}\n"
        "请先用一句话分别说清A和B各是什么，再说两到三个最明显的差异"
        "（如颜色、形状、大小、包装、可见文字），最后用一句话说明最值得注意的区别。"
        "看不清或不确定的不要猜。"
        f"{GROUNDING_RULE}"
        "不要使用 Markdown，不要分点，不超过 100 个字。"
    )
